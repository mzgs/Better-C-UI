"""Generate compact Unicode joining ranges; downloaded UCD data is not vendored."""
import argparse
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{VERSION}/ucd/extracted/DerivedJoiningType.txt"

def generate(text, unicode_data):
    ranges = []
    types = {"L": 1, "R": 2, "D": 3, "C": 3, "T": 4}
    for line in text.splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        points, jt = (part.strip() for part in line.split(";"))
        if jt not in types:
            continue
        ends = points.split("..")
        first, last = int(ends[0], 16), int(ends[-1], 16)
        ranges.append((first, last, types[jt]))
    ranges.sort()
    merged = []
    for first, last, jt in ranges:
        if merged and merged[-1][1] + 1 == first and merged[-1][2] == jt:
            merged[-1] = (merged[-1][0], last, jt)
        else:
            merged.append((first, last, jt))
    assert all(a[1] < b[0] for a, b in zip(merged, merged[1:]))
    assert all(last - first <= 65535 for first, last, jt in merged)
    rows = "\n".join(f"    {{0x{a:x}, {b-a}, {t}}}," for a, b, t in merged)
    result = (f"/* Generated by tools/generate_joining.py from Unicode {VERSION}.\n"
            " * Unicode data licence: https://www.unicode.org/license.txt */\n"
            "static const struct { uint32_t first; uint16_t span; unsigned char type; } cui_joining[] = {\n"
            + rows + "\n};\n")
    compositions, classes = [], []
    for line in unicode_data.splitlines():
        fields = line.split(";")
        cp = int(fields[0], 16)
        if cp > 0x8ff:
            continue
        if int(fields[3]):
            classes.append((cp, int(fields[3])))
        decomposition = fields[5].split()
        if 0x600 <= cp <= 0x8ff and len(decomposition) == 2 and not decomposition[0].startswith("<"):
            compositions.append((cp, *[int(x, 16) for x in decomposition]))
    result += "static const struct { uint16_t cp, base, mark; } cui_compositions[] = {\n"
    result += "\n".join(f"    {{0x{cp:x}, 0x{base:x}, 0x{mark:x}}}," for cp, base, mark in compositions) + "\n};\n"
    result += "static const struct { uint16_t cp; unsigned char value; } cui_combining[] = {\n"
    result += "\n".join(f"    {{0x{cp:x}, {ccc}}}," for cp, ccc in classes) + "\n};\n"
    return result

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, help="Use a local DerivedJoiningType.txt")
    parser.add_argument("--unicode-data", type=Path, help="Use a local UnicodeData.txt")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "src/cui_joining.h")
    args = parser.parse_args()
    text = args.data.read_text(encoding="utf-8") if args.data else urllib.request.urlopen(URL).read().decode("utf-8")
    data = args.unicode_data.read_text(encoding="utf-8") if args.unicode_data else urllib.request.urlopen(f"https://www.unicode.org/Public/{VERSION}/ucd/UnicodeData.txt").read().decode("utf-8")
    args.output.write_text(generate(text, data), encoding="utf-8")

#!/usr/bin/env python3
"""Builds src/cui_emoji_data.h from Unicode's emoji-test.txt.

    python3 tools/gen_emoji.py emoji-test.txt > src/cui_emoji_data.h

Keeps the fully-qualified emoji without skin tones, in Unicode's order and
groups, each with its short name and the version it came in. Skin tones are
made at run time by putting the modifier after each person in the sequence;
an emoji is marked as taking a tone only when that gives exactly the
sequence Unicode lists. The text is stored raw-DEFLATE compressed and is
inflated the first time the picker opens.
"""
import re
import sys
import zlib

TONES = [0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF]


def main():
    src = open(sys.argv[1], encoding="utf-8").read().splitlines()
    date = next((l[8:].strip() for l in src if l.startswith("# Date:")), "")
    version = next((l.split(":")[1].strip() for l in src if l.startswith("# Version:")), "")
    group = None
    items = []          # (group, seq, name, version)
    all_full = set()
    for line in src:
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            continue
        if not line or line.startswith("#"):
            continue
        m = re.match(r"([0-9A-F ]+);\s*(\S+)\s*#\s*\S+\s+E([\d.]+)\s+(.*)", line)
        if not m:
            continue
        seq = tuple(int(c, 16) for c in m.group(1).split())
        if m.group(2) != "fully-qualified":
            continue
        all_full.add(seq)
        if group == "Component" or any(c in TONES for c in seq):
            continue
        items.append((group, seq, m.group(4), m.group(3)))

    # the people a tone goes after: whatever comes right before a tone in any sequence
    bases = set()
    for seq in all_full:
        for i, c in enumerate(seq[1:], 1):
            if c in TONES:
                bases.add(seq[i - 1])

    def toned(seq, tone):
        out = []
        for i, c in enumerate(seq):
            if c == 0xFE0F and out and out[-1] == tone:
                continue          # the tone already asks for the emoji form
            out.append(c)
            if c in bases and not (i > 0 and c == 0x1F91D):   # a handshake joining two people takes none
                out.append(tone)
        return tuple(out)

    versions = sorted({v for _, _, _, v in items}, key=lambda v: tuple(int(x) for x in v.split(".")))
    lines = []
    current = None
    n_tone = 0
    groups = []
    for g, seq, name, ver in items:
        if g != current:
            lines.append("#" + g)
            groups.append(g)
            current = g
        tone = all(toned(seq, t) in all_full for t in TONES) and toned(seq, TONES[0]) != seq
        n_tone += tone
        text = "".join(chr(c) for c in seq)
        lines.append(("+" if tone else "") + text + chr(ord("A") + versions.index(ver)) + name)
    raw = ("\n".join(lines) + "\n").encode("utf-8")
    comp = zlib.compressobj(9, zlib.DEFLATED, -15, 9)
    z = comp.compress(raw) + comp.flush()

    # tone bases as ranges
    ranges = []
    for c in sorted(bases):
        if ranges and ranges[-1][1] == c - 1:
            ranges[-1][1] = c
        else:
            ranges.append([c, c])

    w = sys.stdout.write
    w("/* Generated by tools/gen_emoji.py from Unicode emoji-test.txt %s (%s). See THIRD_PARTY.md.\n" % (version, date))
    w(" * %d emoji in %d groups, %d of them take a skin tone. Each line of the text, once\n" % (len(items), len(groups), n_tone))
    w(" * inflated, is \"#group\" or [+ for a tone] emoji, a version letter, then the name. */\n")
    w("#define CUI__EMOJI_COUNT %d\n#define CUI__EMOJI_RAW_SIZE %d\n" % (len(items), len(raw)))
    w("/* version letters: 'A' + i is version i of: %s */\n" % " ".join(versions))
    w("static const uint32_t cui__emoji_tone_bases[][2] = {\n")
    for i in range(0, len(ranges), 6):
        w("    " + " ".join("{ 0x%05X, 0x%05X }," % (a, b) for a, b in ranges[i:i + 6]) + "\n")
    w("};\n")
    w("static const unsigned char cui__emoji_z[%d] = {\n" % len(z))
    for i in range(0, len(z), 20):
        w("    " + ",".join("%d" % b for b in z[i:i + 20]) + ",\n")
    w("};\n")
    sys.stderr.write("%d emoji, %d toned, raw %d bytes, deflated %d bytes, %d tone ranges\n" % (len(items), n_tone, len(raw), len(z), len(ranges)))


if __name__ == "__main__":
    main()

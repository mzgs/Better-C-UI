"""Generate Unicode 17.0.0 bidi tables from a downloaded UCD directory.

Usage: python tools/gen_bidi.py UCD_DIRECTORY src/cui_bidi_data.h
Inputs: extracted/DerivedBidiClass.txt (or its basename), BidiBrackets.txt,
BidiMirroring.txt. No downloaded data is needed to build CUI.
"""
import pathlib
import re
import sys

CLASSES = 'L R AL EN ES ET AN CS NSM BN B S WS ON LRE LRO RLE RLO PDF LRI RLI FSI PDI'.split()
LONG = dict(zip(['Left_To_Right', 'Right_To_Left', 'Arabic_Letter', 'European_Number', 'European_Separator', 'European_Terminator', 'Arabic_Number', 'Common_Separator', 'Nonspacing_Mark', 'Boundary_Neutral', 'Paragraph_Separator', 'Segment_Separator', 'White_Space', 'Other_Neutral'], CLASSES))

def records(text):
    for line in text.splitlines():
        line = line.split('#')[0].strip()
        if line:
            yield [part.strip() for part in line.split(';')]

def generate(root):
    path = root / 'DerivedBidiClass.txt'
    if not path.exists():
        path = root / 'extracted/DerivedBidiClass.txt'
    text = path.read_text(encoding='utf-8')
    assert 'DerivedBidiClass-17.0.0.txt' in text
    values = bytearray(0x110000)
    missing = re.findall(r'@missing:\s*([0-9A-F.]+);\s*(\w+)', text)
    for span, cls in missing:
        first, _, last = span.partition('..')
        a, b = int(first, 16), int(last or first, 16)
        values[a:b+1] = bytes([CLASSES.index(LONG.get(cls, cls))]) * (b-a+1)
    for span, cls in records(text):
        first, _, last = span.partition('..')
        a, b = int(first, 16), int(last or first, 16)
        values[a:b+1] = bytes([CLASSES.index(cls)]) * (b-a+1)
    transitions = [(i << 5) | v for i, v in enumerate(values) if i == 0 or v != values[i-1]]
    out = ['/* Generated by tools/gen_bidi.py; Unicode 17.0.0. See THIRD_PARTY.md. */', 'static const uint32_t cui__bidi_classes[] = {']
    for i in range(0, len(transitions), 8):
        out.append('    ' + ', '.join('0x%08Xu' % v for v in transitions[i:i+8]) + ',')
    out.append('};')
    out.append('static const struct { uint16_t cp, pair; uint8_t open; } cui__bidi_brackets[] = {')
    for cp, pair, kind in records((root / 'BidiBrackets.txt').read_text(encoding='utf-8')):
        assert max(int(cp, 16), int(pair, 16)) <= 65535
        out.append('    { 0x%s, 0x%s, %d },' % (cp, pair, kind == 'o'))
    out.append('};')
    out.append('static const uint16_t cui__bidi_mirrors[][2] = {')
    for cp, pair in records((root / 'BidiMirroring.txt').read_text(encoding='utf-8')):
        assert max(int(cp, 16), int(pair, 16)) <= 65535
        out.append('    { 0x%s, 0x%s },' % (cp, pair))
    out += ['};', '']
    return '\n'.join(out)

if __name__ == '__main__':
    pathlib.Path(sys.argv[2]).write_text(generate(pathlib.Path(sys.argv[1])), encoding='utf-8')
